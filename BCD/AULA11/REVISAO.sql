-- FASE 1 - DDL

CREATE TABLE USUARIO (
    ID_USUARIO INT AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20),
    ATIVO BOOLEAN DEFAULT TRUE,

    CONSTRAINT PK_ID_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE LIVRO (
    ID_LIVRO INT AUTO_INCREMENT,
    TITULO VARCHAR(200) NOT NULL,
    AUTOR VARCHAR(100) NOT NULL,
    ISBN VARCHAR(20) NOT NULL,
    ANO_PUBLICACAO INT,
    QUANTIDADE_DISPONIVEL INT DEFAULT 0 CHECK (QUANTIDADE_DISPONIVEL >= 0),

    CONSTRAINT PK_ID_LIVRO PRIMARY KEY (ID_LIVRO),
    CONSTRAINT UQ_ISBN UNIQUE (ISBN)
);

CREATE TABLE EMPRESTIMO (
ID_EMPRESTIMO INT AUTO_INCREMENT,
DATA_EMPRESTIMO DATETIME DEFAULT CURRENT_TIMESTAMP,
DATA_PREVISTA DATE NOT NULL,
DATA_DEVOLUCAO DATE,
STATUS_EMPRESTIMO VARCHAR(20) DEFAULT 'ABERTO' CHECK
(STATUS_EMPRESTIMO IN ( 'ABERTO', 'DEVOLVIDO', 'ATRASADO' )),
ID_USUARIO INT NOT NULL,
ID_LIVRO INT NOT NULL,

CONSTRAINT PK_EMPRESTIMO PRIMARY KEY (ID_EMPRESTIMO),
CONSTRAINT FK_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES
USUARIO (ID_USUARIO),
CONSTRAINT FK_LIVRO FOREIGN KEY (ID_LIVRO) REFERENCES LIVRO
(ID_LIVRO)
);

CREATE TABLE CATEGORIA (
    ID_CATEGORIA INT AUTO_INCREMENT,
    NOME_CATEGORIA VARCHAR(100) NOT NULL UNIQUE,
    ID_LIVRO INT NOT NULL,
    
    CONSTRAINT PK_ID_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UQ_NOME_CATEGORIA UNIQUE (NOME_CATEGORIA),
    CONSTRAINT FK_CATEGORIA_LIVRO FOREIGN KEY (ID_LIVRO) REFERENCES LIVRO (ID_LIVRO)
);


